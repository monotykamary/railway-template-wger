import { readFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import assert from 'node:assert/strict';
const d=readFileSync('Dockerfile','utf8'),e=readFileSync('entrypoint.sh','utf8'),r=readFileSync('run.sh','utf8'),c=readFileSync('Caddyfile','utf8');
assert.match(d,/wger\/server:2\.7\.0@sha256:[a-f0-9]{64}/);
assert.match(d,/caddy:2\.11\.9-alpine@sha256:[a-f0-9]{64}/);
assert.doesNotMatch(d,/:latest/);
assert.match(e,/setpriv/);
assert.match(r,/generate-jwt-keys/);
assert.match(r,/set_password/);
assert.match(c,/handle_path \/media/);
const originalSHA='633c50087916598c2a68704bfc43c7df9c924c5abf12560d7212e41098b4a7cd';
const settings=readFileSync('settings_main.py','utf8');
const marker='\n# Railway wrapper adaptation: HTTPS-only browser cookies (secure-cookie-v1).\n';
const i=settings.indexOf(marker);
assert.ok(i>0);
assert.equal(createHash('sha256').update(settings.slice(0,i)).digest('hex'),originalSHA);
assert.deepEqual(settings.slice(i).split('\n').filter(line=>line.trim()&&!line.trim().startsWith('#')),['SESSION_COOKIE_SECURE = True','CSRF_COOKIE_SECURE = True']);
assert.ok(d.includes(`RUN echo '${originalSHA}  /home/wger/src/settings/main.py' | sha256sum -c -`));
assert.ok(d.includes('COPY settings_main.py /home/wger/src/settings/main.py'));
console.log('static template and secure-cookie source checks passed');
